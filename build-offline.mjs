import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = dirname(fileURLToPath(import.meta.url));
const modules = [
  ['config.js', ['CONFIG']],
  ['physics.js', ['terrainHeight', 'terrainSlope', 'terrainCurvature', 'hasGround', 'newStage', 'stepStage']],
  ['camera.js', ['updateCamera']],
  ['scoring.js', ['newRun', 'collectCoin', 'landingPoints', 'loseLife']],
  ['audio.js', ['createAudio']],
  ['render.js', ['render']],
  ['main.js', []]
];

function transform(source, filename) {
  const imports = [];
  const withoutImports = source.replace(/^import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"];?\s*$/gm, (_, names, dependency) => {
    imports.push(`const { ${names.trim().replace(/\s+as\s+/g, ': ')} } = modules[${JSON.stringify(dependency)}];`);
    return '';
  });
  if (/^\s*import\b/m.test(withoutImports)) throw new Error(`Unsupported import in ${filename}`);
  const body = withoutImports.replace(/\bexport\s+(?=(?:const|let|function|class)\b)/g, '');
  if (/\bexport\b/.test(body)) throw new Error(`Unsupported export in ${filename}`);
  return `${imports.join('\n')}\n${body}`;
}

export async function bundleSource() {
  const sourceFiles = await Promise.all(modules.map(([filename]) => readFile(resolve(root, 'src', filename), 'utf8')));
  const digest = createHash('sha256').update(sourceFiles.join('\n/* next module */\n')).digest('hex');
  const output = [
    '// Generated by build-offline.mjs. Edit src/*.js, then run npm run build:offline.',
    `// Source SHA-256: ${digest}`,
    '(function () {',
    "'use strict';",
    'const modules = Object.create(null);'
  ];
  modules.forEach(([filename, names], index) => {
    output.push(`modules[${JSON.stringify(filename)}] = (function () {`);
    output.push(transform(sourceFiles[index], filename));
    output.push(`return { ${names.join(', ')} };`);
    output.push('})();');
  });
  output.push('})();', '');
  return output.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputFile = resolve(root, 'src', 'game-classic.js');
  await writeFile(outputFile, await bundleSource(), 'utf8');
  console.log(`Built ${outputFile}`);
}
